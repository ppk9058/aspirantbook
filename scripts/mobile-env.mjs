import os from "node:os";
import fs from "node:fs";
import path from "node:path";
import qrcode from "qrcode-terminal";

/**
 * Detects the machine's primary local area network (LAN) IPv4 address.
 * Prioritizes active Wi-Fi and Ethernet adapters (en0, eth0, wlan0) while
 * filtering out virtual bridges, loopbacks, and tunnel interfaces.
 */
export function getLanIp() {
  const interfaces = os.networkInterfaces();
  const candidates = [];

  for (const [name, addrs] of Object.entries(interfaces)) {
    if (!addrs) continue;
    const lowerName = name.toLowerCase();

    // Ignore virtual / containerized / loopback interfaces
    if (
      lowerName.startsWith("lo") ||
      lowerName.startsWith("docker") ||
      lowerName.startsWith("br-") ||
      lowerName.startsWith("veth") ||
      lowerName.startsWith("utun") ||
      lowerName.startsWith("awdl") ||
      lowerName.startsWith("llw")
    ) {
      continue;
    }

    for (const addr of addrs) {
      if (addr.family === "IPv4" || addr.family === 4) {
        if (!addr.internal && addr.address !== "127.0.0.1") {
          const isPreferred =
            lowerName.startsWith("en") ||
            lowerName.startsWith("eth") ||
            lowerName.startsWith("wlan");
          candidates.push({
            address: addr.address,
            name,
            priority: isPreferred ? 1 : 2,
          });
        }
      }
    }
  }

  candidates.sort((a, b) => a.priority - b.priority);
  return candidates[0]?.address || "127.0.0.1";
}

/**
 * Writes the detected LAN IP into apps/mobile/.env.local and outputs instructions with QR code.
 */
export function configureMobileEnv() {
  const lanIp = getLanIp();
  const envFilePath = path.resolve("apps/mobile/.env.local");
  const envContent = `# Automatically generated by scripts/mobile-env.mjs\n# Generated at: ${new Date().toISOString()}\nEXPO_PUBLIC_API_URL=http://${lanIp}:3045\n`;

  fs.writeFileSync(envFilePath, envContent, "utf-8");

  console.log("\n=======================================================");
  console.log("🚀 ASPIRANTBOOK MOBILE - LAN ENVIRONMENT CONFIGURATION");
  console.log("=======================================================");
  console.log(`Detected LAN IP:           ${lanIp}`);
  console.log(`Web Test API Server:       http://${lanIp}:3045`);
  console.log(`Configured File:           ${envFilePath}`);
  console.log(`Expo Metro URL:            exp://${lanIp}:8081`);
  console.log("-------------------------------------------------------");
  console.log("TEST CREDENTIALS (Pre-seeded on Docker Test DB: 54329):");
  console.log("1. GUEST USER:       No login required (free preview & 20% slice)");
  console.log("2. STUDENT (PRO):    student.mobile@aspirantbook.com / Student123!");
  console.log("                     (Active subscription, 2 pre-seeded mock attempts)");
  console.log("3. ADMIN / TEACHER:  admin.mobile@aspirantbook.com / Admin123!");
  console.log("                     (Full administrative & test series management)");
  console.log("-------------------------------------------------------");
  console.log("Scan with Expo Go (Android camera / iOS Camera app):\n");

  try {
    qrcode.generate(`exp://${lanIp}:8081`, { small: true });
  } catch {
    console.log(`Open in Expo Go: exp://${lanIp}:8081`);
  }

  console.log("=======================================================\n");
  return lanIp;
}

if (process.argv[1]?.endsWith("mobile-env.mjs")) {
  configureMobileEnv();
}
